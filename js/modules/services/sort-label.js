/**
 * Подпись выбранной сортировки для триггера выпадашки.
 *
 * Разметка опций (`.ui-sort__option`) переносится форматтером по ширине строки,
 * поэтому в `textContent` попадает перенос с отступом: «По цене\n  (убывание)».
 * `trim()` его не убирает — подпись рвалась на две строки и триггер прыгал.
 * Здесь пробельные последовательности схлопываются в один пробел.
 */
export const sortLabel = (el) => (el?.textContent || "").replace(/\s+/g, " ").trim();
